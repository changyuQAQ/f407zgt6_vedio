#ifndef __TFT_INIT_H
#define __TFT_INIT_H

#include "stm32f4xx.h"
#include <stdio.h>

/* ============================================================================
 *  直接复用你已经调通的 ILI9488 驱动（FSMC Bank1-NORSRAM4 + A6/RS）
 *  本文件把 tft.c 依赖的 6 个底层函数，适配到 lcd_ili9488.c 上。
 *  lcd_ili9488.c / lcd_ili9488.h 不要改动。
 * ========================================================================== */
#include "lcd_ili9488.h"

/* ============================================================================
 *  屏幕分辨率
 *
 *  ★★★ 必须填"整屏"分辨率，不能填视频窗口大小！★★★
 *
 *  原因：tft.c 的 TFT_DrawPicture_DMA() 开头有
 *          if(x >= LCD_W || y >= LCD_H) return;
 *  160x128 视频在 320x480 竖屏上居中后，起始坐标 y = 176。
 *  如果这里还是 160/128，那么 176 >= 128 成立 → 直接 return，
 *  一个像素都不会画，而且编译是 0 错误 0 警告，极容易误判成时序问题。
 * ========================================================================== */
#define LCD_W   LCD_WIDTH       /* lcd_ili9488.h 里是 320 */
#define LCD_H   LCD_HEIGHT      /* lcd_ili9488.h 里是 480 */

/* ============================================================================
 *  视频窗口（160x128 居中）
 *    320x480 竖屏（MADCTL=0x88）  →  (80, 176)
 *    480x320 横屏（MADCTL=0x28）  →  (160, 96)
 * ========================================================================== */
#define VIDEO_X0   ((LCD_W - VIDEO_WIDTH ) / 2)
#define VIDEO_Y0   ((LCD_H - VIDEO_HEIGHT) / 2)

/* ============================================================================
 *  低层接口 —— tft.c 全文只依赖这 6 个函数
 * ========================================================================== */
void TFT_Init(void);
void TFT_WR_REG(uint8_t reg);
void TFT_WR_DATA8(uint8_t data);
void TFT_WR_DATA(uint16_t data);
void TFT_WR_DATA_DMA(uint8_t *buff, uint32_t len);   /* ★ len 必须是 uint32_t */
void TFT_Address_Set(uint16_t x1, uint16_t y1, uint16_t x2, uint16_t y2);

#endif /* __TFT_INIT_H */
